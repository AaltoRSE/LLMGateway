def create_jwt_token(  # pylint: disable=too-many-arguments
    private_key: RSAPrivateKey,
    auth_id: str,
    groups: list[str],
    exp: datetime.timedelta = datetime.timedelta(hours=1),
    first: str = "John",
    last: str = "Doe",
    field_set: dict[str, Any] | None = None,
    key_id: str | None = KEY_ID,
) -> str:
    """
    sample token as generated by Entra ID for Aalto AI:

    {
        'aud': 'api://f9f02fa3-9d55-422b-9dd1-1942471b27c4',
        'iss': 'https://sts.windows.net/ae1a7724-4041-4462-a6dc-538cb199707e/',
        'iat': 1742285333,
        'nbf': 1742285333,
        'exp': 1742289422,
        'acr': '1',
        'aio': '[long base64 encoded code]',
        'amr': ['mfa'],
        'appid': 'f9f02fa3-9d55-422b-9dd1-1942471b27c4',
        'appidacr': '0',
        'family_name': 'Lastname',
        'given_name': 'Firstname',
        'groups': ['406a54fc-6ee1-4909-8ebe-280381547528', '3ab7ddd2-16f3-4736-853c-f1f7f2c00c68', 'b050d1ca-73db-4045-8534-6288a93dab89', '06380dba-3e56-45e4-bbf4-37235a864775'],
        'ipaddr': '2001:708:....[rest]',
        'name': 'Lastname Firstname',
        'oid': '[uuid]',
        'onprem_sid': 'S-1-5-21-2413826791-....',
        'rh': '1.something.',
        'scp': 'AaltoAI.Access',
        'sid': '[uuid]
        'sub': '[value]
        'tid': '[uuid]
        'unique_name': 'email@aalto.fi',
        'upn': 'email@aalto.fi',
        'uti': '[value]',
        'ver': '1.0'
    }
    """

    if field_set is None:
        field_set = {}

    now = datetime.datetime.now(datetime.timezone.utc)
    payload: dict[str, Any] = {
        "scp": "AaltoAI.Access",
        "groups": groups,
        "given_name": first,
        "family_name": last,
        "unique_name": auth_id,
        "aud": AUDIENCE,
        "iss": f"https://sts.windows.net/{TENANT_ID}/",
        "iat": now,
        "exp": now + exp,
        "ver": "1.0",
        "tid": TENANT_ID,
    }

    for field, value in field_set.items():
        if value is None:
            del payload[field]
        else:
            payload[field] = value

    headers = {}
    if key_id is not None:
        headers["kid"] = key_id

    token = jwt.encode(payload, private_key, algorithm="RS256", headers={"kid": key_id})

    return token


def create_user_token(  # pylint: disable=too-many-arguments
    auth_id: str,
    groups: list[str],
    first: str = "John",
    last: str = "Doe",
    timedelta: datetime.timedelta = datetime.timedelta(hours=1),
    private_key: RSAPrivateKey = priv_key,
    field_set: dict[str, Any] | None = None,
    key_id: str | None = KEY_ID,
) -> str:
    return create_jwt_token(
        private_key=private_key,
        auth_id=auth_id,
        groups=groups,
        exp=timedelta,
        first=first,
        last=last,
        field_set=field_set,
        key_id=key_id,
    )


def create_token_for_user(
    user: User,
    roles: list[str],
    private_key: RSAPrivateKey = priv_key,
    timedelta: datetime.timedelta = datetime.timedelta(hours=1),
    field_set: dict[str, Any] | None = None,
    key_id: str | None = KEY_ID,
) -> str:
    return create_user_token(
        auth_id=user.auth_id,
        groups=roles,
        first=user.first_name,
        last=user.last_name,
        timedelta=timedelta,
        private_key=private_key,
        field_set=field_set,
        key_id=key_id,
    )
